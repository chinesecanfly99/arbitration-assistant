@dataclass
class Round:
    hr_says: str
    why: str
    counter: str
    need: list[str] = field(default_factory=list)


def rehearsal(cause: str, fields: dict | None = None, max_rounds: int = 3) -> dict:
    """按案由挑最可能被 HR 拿出来打的三轮抗辩。"""
    fields = fields or {}
    rounds = [Round(**c) for c in COMMON[:1]]
    rounds += [Round(**c) for c in BY_CAUSE.get(cause, [])]
    if len(rounds) < max_rounds:
        rounds += [Round(**c) for c in COMMON[1:2]]
    rounds = rounds[:max_rounds]

    need = []
    for r in rounds:
        for n in r.need:
            if n not in need:
                need.append(n)
    return {
        "cause": cause,
        "rounds": [r.__dict__ for r in rounds],
        "evidence_checklist": need,
        "tip": "把这几个问题按顺序问自己：谁先提的解除、有没有书面文件、钱是谁发的、制度有没有公示、聊天记录还在不在。",
    }
