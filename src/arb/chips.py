def suggest(story: str, limit: int = 6) -> list[dict]:
    """按故事里的线索推荐芯片：先命中触发词，再退化成宽松的"when 文案重叠"。"""
    low = story or ""
    hits: list[tuple[int, dict]] = []
    for c in CHIPS:
        score = 0
        for kw in TRIGGERS.get(c["term"], []):
            if kw in low:
                score += 2
        if score == 0:
            continue
        if c["group"] == "证据":
            score -= 1
        hits.append((score, c))
    hits.sort(key=lambda x: -x[0])
    return [c for _, c in hits[:limit]]
