def main() -> int:
    seen = set()
    rows = []
    for c in CASES:
        assert c["id"] not in seen, f"重复 id {c['id']}"
        seen.add(c["id"])
        for cite in c["must_cite"]:
            slug, _, no = cite.partition(":")
            assert laws.exists(slug, no), f"{c['id']} 引用不存在：{cite}"
        g = {k: (date.fromisoformat(v) if k in {"hire_date", "end_date", "contract_signed_date"} and isinstance(v, str) else v)
             for k, v in c["gold"].items()}
        res = compute(ClaimInput(**g))
        row = dict(c)
        row["expected"] = {
            "items": [{"name": i["name"], "amount": i["amount"], "basis": i["basis"]} for i in res["items"]],
            "total": res["total"],
            "service_months": res["service_months"],
            "severance_months": res["severance_months"],
        }
        row["source"] = SRC
        rows.append(row)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    by_cause: dict[str, int] = {}
    for r in rows:
        by_cause[r["cause"]] = by_cause.get(r["cause"], 0) + 1
    print(f"写入 {len(rows)} 条 -> {OUT}")
    print("按案由：", by_cause)
    print("总额区间：", min(r["expected"]["total"] for r in rows), "-", max(r["expected"]["total"] for r in rows))
    return 0


